  /* ---------- Geometry & interpolation helpers ---------- */

  function clamp(val, min, max) {
    return val < min ? min : val > max ? max : val;
  }

  function smoothstep(edge0, edge1, x) {
    var t = clamp((x - edge0) / (edge1 - edge0), 0, 1);
    return t * t * (3 - 2 * t);
  }

  function polygonCentroid(pts) {
    var cx = 0;
    var cy = 0;
    for (var i = 0; i < pts.length; i += 1) {
      cx += pts[i][0];
      cy += pts[i][1];
    }
    return [cx / pts.length, cy / pts.length];
  }

  /* Resample any closed polygon to N evenly spaced perimeter points,
     starting from the point closest to the top-left (-3pi/4) angle around
     its centroid so morphing between keyframes never twists.
  */
  function resamplePolygon(pts, count) {
    var n = pts.length;
    var segLengths = [];
    var total = 0;
    var i;

    for (i = 0; i < n; i += 1) {
      var a = pts[i];
      var b = pts[(i + 1) % n];
      var len = Math.hypot(b[0] - a[0], b[1] - a[1]);
      segLengths.push(len);
      total += len;
    }

    if (total === 0) {
      var fallback = [];
      for (i = 0; i < count; i += 1) {
        fallback.push([pts[0][0], pts[0][1]]);
      }
      return fallback;
    }

    var raw = [];
    var step = total / count;
    var segIdx = 0;
    var segStart = 0;

    for (i = 0; i < count; i += 1) {
      var target = i * step;
      while (segIdx < n - 1 && segStart + segLengths[segIdx] < target) {
        segStart += segLengths[segIdx];
        segIdx += 1;
      }
      var segLen = segLengths[segIdx] || 1;
      var frac = clamp((target - segStart) / segLen, 0, 1);
      var p0 = pts[segIdx];
      var p1 = pts[(segIdx + 1) % n];
      raw.push([p0[0] + (p1[0] - p0[0]) * frac, p0[1] + (p1[1] - p0[1]) * frac]);
    }

    /* Rotate start index to canonical angle (-3pi/4) for twist-free morphing */
    var center = polygonCentroid(raw);
    var bestIdx = 0;
    var bestDiff = Infinity;
    var targetAngle = -Math.PI * 0.75;

    for (i = 0; i < count; i += 1) {
      var ang = Math.atan2(raw[i][1] - center[1], raw[i][0] - center[0]);
      var diff = Math.abs(Math.atan2(Math.sin(ang - targetAngle), Math.cos(ang - targetAngle)));
      if (diff < bestDiff) {
        bestDiff = diff;
        bestIdx = i;
      }
    }

    var aligned = [];
    for (i = 0; i < count; i += 1) {
      aligned.push(raw[(bestIdx + i) % count]);
    }
    return aligned;
  }

  function preparePolities() {
    var prepared = [];
    for (var i = 0; i < POLITIES.length; i += 1) {
      var src = POLITIES[i];
      var frames = [];
      for (var j = 0; j < src.frames.length; j += 1) {
        var pts = resamplePolygon(src.frames[j].p, SAMPLE_COUNT);
        frames.push({
          y: src.frames[j].y,
          p: pts,
          c: polygonCentroid(pts)
        });
      }
      prepared.push({
        id: src.id,
        color: PALETTE[src.tone] || PALETTE.stone,
        z: src.z || 10,
        fadeIn: src.fadeIn || 30,
        fadeOut: src.fadeOut || 30,
        frames: frames
      });
    }
    prepared.sort(function (a, b) {
      return a.z - b.z;
    });
    return prepared;
  }

